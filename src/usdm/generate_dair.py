def _load_amendment_for_freeze(soa_id: int, revised_freeze_id: int) -> Optional[Dict]:
    from soa_builder.web.db import _connect

    conn = _connect()
    cur = conn.cursor()
    cur.execute(
        "SELECT id, amendment_uid, name, number, summary, label, description"
        " FROM study_amendment WHERE soa_id=? AND freeze_id=?",
        (soa_id, revised_freeze_id),
    )
    row = cur.fetchone()
    if not row:
        conn.close()
        return None

    amend_uid = row[1]
    amendment = {
        "id": row[0],
        "amendment_uid": amend_uid,
        "name": row[2],
        "number": row[3],
        "summary": row[4],
        "label": row[5],
        "description": row[6],
    }

    cur.execute(
        "SELECT role, code_uid, other_reason FROM study_amendment_reason"
        " WHERE soa_id=? AND amendment_uid=?",
        (soa_id, amend_uid),
    )
    amendment["reasons"] = [
        {"role": r[0], "code_uid": r[1], "other_reason": r[2]} for r in cur.fetchall()
    ]

    cur.execute(
        "SELECT impact_uid, type_code_uid, text, is_substantial"
        " FROM study_amendment_impact WHERE soa_id=? AND amendment_uid=?",
        (soa_id, amend_uid),
    )
    amendment["impacts"] = [
        {
            "impact_uid": r[0],
            "type_code_uid": r[1],
            "text": r[2],
            "is_substantial": bool(r[3]),
        }
        for r in cur.fetchall()
    ]

    cur.execute(
        "SELECT change_uid, name, label, summary, rationale"
        " FROM study_change WHERE soa_id=? AND amendment_uid=?",
        (soa_id, amend_uid),
    )
    changes = []
    for crow in cur.fetchall():
        change_uid = crow[0]
        cur2 = conn.cursor()
        cur2.execute(
            "SELECT section_number, section_title"
            " FROM document_content_reference"
            " WHERE soa_id=? AND change_uid=?",
            (soa_id, change_uid),
        )
        changes.append(
            {
                "change_uid": change_uid,
                "name": crow[1],
                "label": crow[2],
                "summary": crow[3],
                "rationale": crow[4],
                "sections": [
                    {"section_number": r[0], "section_title": r[1]}
                    for r in cur2.fetchall()
                ],
            }
        )
    amendment["changes"] = changes

    cur.execute(
        "SELECT scope_uid, type_code_uid FROM amendment_geographic_scope"
        " WHERE soa_id=? AND amendment_uid=?",
        (soa_id, amend_uid),
    )
    amendment["geographic_scopes"] = [
        {"scope_uid": r[0], "type_code_uid": r[1]} for r in cur.fetchall()
    ]

    cur.execute(
        "SELECT enrollment_uid, name, quantity_value"
        " FROM amendment_subject_enrollment WHERE soa_id=? AND amendment_uid=?",
        (soa_id, amend_uid),
    )
    amendment["enrollments"] = [
        {"enrollment_uid": r[0], "name": r[1], "quantity_value": r[2]}
        for r in cur.fetchall()
    ]

    cur.execute(
        "SELECT date_uid, name, type_code_uid, date_value"
        " FROM amendment_governance_date WHERE soa_id=? AND amendment_uid=?",
        (soa_id, amend_uid),
    )
    amendment["governance_dates"] = [
        {"date_uid": r[0], "name": r[1], "type_code_uid": r[2], "date_value": r[3]}
        for r in cur.fetchall()
    ]

    conn.close()
    return amendment


