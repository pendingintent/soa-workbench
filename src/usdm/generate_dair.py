"""Generate a Digital Amendment Impact Report (DAIR) as a DOCX file.

Compares two freeze snapshots of an SoA and renders the structural
diff plus downstream standards-layer impact signals into a DOCX
document matching the layout of files/Digital_Amendment_Impact_Report_DAIR.docx.
"""

