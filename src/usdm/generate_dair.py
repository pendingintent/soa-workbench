def build_dair(soa_id: int, base_freeze_id: int, revised_freeze_id: int) -> bytes:
    """Build and return a DAIR DOCX as bytes."""
    from soa_builder.web.routers._freeze_helpers import (
        _diff_freezes,
        _get_freeze,
    )
    from soa_builder.web.db import _connect

    base_freeze = _get_freeze(soa_id, base_freeze_id)
    revised_freeze = _get_freeze(soa_id, revised_freeze_id)
    if not base_freeze:
        raise ValueError(
            f"Base freeze id={base_freeze_id} not found for soa_id={soa_id}"
        )
    if not revised_freeze:
        raise ValueError(
            f"Revised freeze id={revised_freeze_id} not found for soa_id={soa_id}"
        )

    diff = _diff_freezes(soa_id, base_freeze_id, revised_freeze_id)

    conn = _connect()
    cur = conn.cursor()
    cur.execute("SELECT name, study_label FROM soa WHERE id=?", (soa_id,))
    row = cur.fetchone()
    conn.close()
    soa_name = row[0] if row else f"SoA {soa_id}"
    study_label = row[1] if row else None

    amendment = _load_amendment_for_freeze(soa_id, revised_freeze_id)
    downstream = _infer_downstream(diff)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    return _build_docx(
        soa_name=soa_name,
        study_label=study_label,
        base_label=base_freeze["version_label"],
        revised_label=revised_freeze["version_label"],
        base_created=base_freeze["created_at"],
        revised_created=revised_freeze["created_at"],
        diff=diff,
        amendment=amendment,
        downstream=downstream,
        generated_at=generated_at,
    )
