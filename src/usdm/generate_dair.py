# Cell shading colors (hex, no '#')
_COLOR_DIRECT = "C6EFCE"  # green  – Direct / High confidence
_COLOR_INFERRED_MED = "FFEB9C"  # amber  – Strongly inferred
_COLOR_INFERRED_LOW = "FFC7CE"  # pink   – Weakly inferred
_COLOR_HEADER = "2E4057"  # dark slate – table header bg
_COLOR_COVER = "1F3864"  # navy   – cover title bg
_COLOR_COVER_SUB = "3A5A8C"  # blue   – cover subtitle bg

_IMPACT_HIGH = "High"
_IMPACT_MED = "Medium"
_IMPACT_LOW = "Low"

# Content width in DXA for a US Letter page with 0.75" side margins
# 12240 - 1080 - 1080 = 10080
_CW = 10080

_FOOTER_TEXT = (
    "Generated by 360i SoA Workbench · USDM version comparison · "
    "This report is a machine-generated change intelligence artifact. "
    "It is not a regulatory document. "
    "Study team review is required before acting on inferred impacts."
)


