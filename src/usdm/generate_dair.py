def _build_docx(
    soa_name: str,
    study_label: Optional[str],
    base_label: str,
    revised_label: str,
    base_created: str,
    revised_created: str,
    diff: Dict,
    amendment: Optional[Dict],
    downstream: Dict,
    generated_at: str,
) -> bytes:
    doc = Document()

    # US Letter, 0.75" side margins, 0.5" top/bottom
    for section in doc.sections:
        section.page_width = Inches(8.5)  # US Letter
        section.page_height = Inches(11)
        section.left_margin = Inches(0.75)
        section.right_margin = Inches(0.75)
        section.top_margin = Inches(0.5)
        section.bottom_margin = Inches(0.5)

    _add_footer(doc)

    # ── convenience shortcuts ──────────────────────────────────────────────

    def h1(text: str):
        p = doc.add_heading(text, level=1)
        p.runs[0].font.size = Pt(14)
        return p

    def h2(text: str):
        p = doc.add_heading(text, level=2)
        p.runs[0].font.size = Pt(11)
        return p

    def body(text: str, italic: bool = False):
        p = doc.add_paragraph()
        run = p.add_run(text)
        run.font.size = Pt(10)
        run.italic = italic
        return p

    def spacer():
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(4)

    # ── column-width presets ───────────────────────────────────────────────
    # All widths must sum to _CW = 10080

    # Cover meta: label narrow, value wide, label narrow, value wide
    _META_COLS = [1728, 3312, 1728, 3312]  # = 10080
