def _classify_impact(entity_key: str, change_type: str) -> str:
    high_entities = {"endpoints", "objectives"}
    low_entities = {"bc_properties", "extension_attributes"}
    if entity_key in high_entities:
        return _IMPACT_HIGH
    if entity_key in low_entities:
        return _IMPACT_LOW
    if entity_key == "activities" and change_type in ("added", "removed"):
        return _IMPACT_MED
    if entity_key in ("biomedical_concepts", "bc_surrogates"):
        return _IMPACT_MED
    if entity_key in ("arms", "epochs", "elements"):
        return _IMPACT_MED if change_type == "added" else _IMPACT_LOW
    if entity_key in ("timings", "schedule_timelines", "instances"):
        return _IMPACT_MED
    return _IMPACT_LOW


