def _item_name(item: Dict) -> str:
    for key in ("name", "label", "text", "summary"):
        v = item.get(key)
        if v:
            return str(v)
    for key in item:
        if key.endswith("_uid"):
            return item[key]
    return str(item)


def _changed_detail(change: Dict) -> List[str]:
    """Return detail lines for a modified entity (one line per changed field)."""
    lines = []
    for field, vals in change.get("changes", {}).items():
        old_v = vals.get("old") or "(empty)"
        new_v = vals.get("new") or "(empty)"
        lines.append(f"{field}: Was: {old_v} / Now: {new_v}")
    return lines or ["Modified"]


