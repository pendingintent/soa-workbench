def _set_table_col_widths(table, col_widths_dxa: List[int]):
    """Force explicit DXA widths on table, tblGrid, and every cell.

    Must be called AFTER all rows have been added to the table so every
    cell receives its width.
    """
    total = sum(col_widths_dxa)
    tbl = table._tbl
    tblPr = tbl.find(qn("w:tblPr"))

    # Set tblW to the total
    if tblPr is not None:
        tblW = tblPr.find(qn("w:tblW"))
        if tblW is None:
            tblW = OxmlElement("w:tblW")
            tblPr.append(tblW)
        tblW.set(qn("w:type"), "dxa")
        tblW.set(qn("w:w"), str(total))

    # Replace tblGrid with explicit column widths
    existing = tbl.find(qn("w:tblGrid"))
    if existing is not None:
        tbl.remove(existing)
    tblGrid = OxmlElement("w:tblGrid")
    if tblPr is not None:
        tblPr.addnext(tblGrid)
    else:
        tbl.insert(0, tblGrid)
    for w in col_widths_dxa:
        gc = OxmlElement("w:gridCol")
        gc.set(qn("w:w"), str(w))
        tblGrid.append(gc)

    # Set explicit tcW on every cell
    for row in table.rows:
        for i, cell in enumerate(row.cells):
            if i >= len(col_widths_dxa):
                break
            tcPr = cell._tc.get_or_add_tcPr()
            tcW = tcPr.find(qn("w:tcW"))
            if tcW is None:
                tcW = OxmlElement("w:tcW")
                tcPr.append(tcW)
            tcW.set(qn("w:type"), "dxa")
            tcW.set(qn("w:w"), str(col_widths_dxa[i]))


def _set_cell_shading(cell, hex_color: str):
    tc = cell._tc
    tcp = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcp.append(shd)


def _set_font(
    run,
    size_pt: int,
    bold: bool = False,
    color_hex: Optional[str] = None,
    italic: bool = False,
):
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size_pt)
    if color_hex:
        r, g, b = (
            int(color_hex[0:2], 16),
            int(color_hex[2:4], 16),
            int(color_hex[4:6], 16),
        )
        run.font.color.rgb = RGBColor(r, g, b)


def _cell_para(cell, align=WD_ALIGN_PARAGRAPH.LEFT):
    """Return the cell's first paragraph with alignment set."""
    para = cell.paragraphs[0]
    para.alignment = align
    return para


def _add_cell_text(
    cell,
    text: str,
    size_pt: int = 9,
    bold: bool = False,
    italic: bool = False,
    align=WD_ALIGN_PARAGRAPH.LEFT,
    color_hex: Optional[str] = None,
):
    """Write text into the cell's first paragraph."""
    para = _cell_para(cell, align)
    run = para.add_run(str(text))
    _set_font(run, size_pt, bold=bold, italic=italic, color_hex=color_hex)
    return para


def _add_cell_lines(
    cell,
    lines: List[str],
    size_pt: int = 9,
    bold: bool = False,
    italic: bool = False,
    align=WD_ALIGN_PARAGRAPH.LEFT,
    color_hex: Optional[str] = None,
):
    """Write multiple lines into a cell, one paragraph per line."""
    for i, line in enumerate(lines):
        if i == 0:
            para = _cell_para(cell, align)
        else:
            para = cell.add_paragraph()
            para.alignment = align
        run = para.add_run(str(line))
        _set_font(run, size_pt, bold=bold, italic=italic, color_hex=color_hex)


def _header_row(
    table, headers: List[str], bg_hex: str = _COLOR_HEADER, text_color: str = "FFFFFF"
):
    """Fill table row 0 as a coloured header."""
    row = table.rows[0]
    for i, hdr in enumerate(headers):
        cell = row.cells[i]
        _set_cell_shading(cell, bg_hex)
        _add_cell_text(
            cell,
            hdr,
            size_pt=9,
            bold=True,
            color_hex=text_color,
            align=WD_ALIGN_PARAGRAPH.CENTER,
        )


def _add_footer(doc: Document):
    section = doc.sections[0]
    footer = section.footer
    para = footer.paragraphs[0]
    para.clear()
    run = para.add_run(_FOOTER_TEXT)
    _set_font(run, 7, italic=True, color_hex="666666")
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER


def _confidence_color(confidence: str) -> str:
    if confidence == "direct":
        return _COLOR_DIRECT
    if confidence == "inferred_med":
        return _COLOR_INFERRED_MED
    return _COLOR_INFERRED_LOW


def _confidence_label(confidence: str) -> str:
    if confidence == "direct":
        return "High (Direct)"
    if confidence == "inferred_med":
        return "Medium (Inferred)"
    return "Low (Inferred)"


