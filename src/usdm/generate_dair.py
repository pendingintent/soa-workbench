def _derive_actions(signals: Dict[str, List[Dict]]) -> List[Dict]:
    actions = []
    seen: set = set()

    def _add(action, owner, basis, impact, source):
        key = (action, owner)
        if key not in seen:
            seen.add(key)
            actions.append(
                {
                    "action": action,
                    "owner": owner,
                    "basis": basis,
                    "impact": impact,
                    "source": source,
                }
            )

    for s in signals.get("sdtm", []):
        if s["impact"] == _IMPACT_HIGH:
            _add(
                f"Update SDTM mapping specifications — {s['module']} domain",
                "DM / Programming",
                s["usdm_change"],
                _IMPACT_HIGH,
                "Inferred",
            )
    for s in signals.get("adam", []):
        if s["impact"] == _IMPACT_HIGH:
            _add(
                f"Update ADaM specs — {s['module']}",
                "Programming / Stats",
                s["usdm_change"],
                _IMPACT_HIGH,
                "Inferred",
            )
    for s in signals.get("ecrf", []):
        if s["impact"] in (_IMPACT_HIGH, _IMPACT_MED):
            _add(
                f"Rebuild eCRF modules — {s['module']}",
                "EDC Team / DM",
                s["usdm_change"],
                s["impact"],
                "Direct",
            )
    for s in signals.get("tlf", []):
        if s["impact"] == _IMPACT_HIGH:
            _add(
                f"Update TLF shells — {s['module']}",
                "Programming / Stats",
                s["usdm_change"],
                _IMPACT_HIGH,
                "Inferred",
            )
    return actions


